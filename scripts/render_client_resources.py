"""Render each client's bundle resources from its client YAML (no hand edits needed):

  resources/clients/<client>.yml          its silver+gold pipeline and its orchestration job
  dashboards/<client>.lvdash.json         its AI/BI dashboard (from dashboards/gold_overview.template.json)

Onboarding a client = config/clients/<client>.yml (+ any new source YAMLs), then run this script.
The generated files are committed so the bundle is reviewable; they carry a do-not-edit header.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from keelstone.config import load_client  # noqa: E402

HEADER = "# GENERATED by scripts/render_client_resources.py from config/clients/{client}.yml. Do not edit.\n"


def nb(path: str, **params) -> dict:
    return {"notebook_task": {"notebook_path": f"../../jobs/{path}", "base_parameters": params}}


def resources(c) -> dict:
    cid = c.client_id
    pipe = f"pipeline_{cid}"
    pid = f"${{resources.pipelines.{pipe}.id}}"
    jp = lambda name: f"{{{{job.parameters.{name}}}}}"  # noqa: E731
    t = lambda key, deps=None, run_if=None, retries=0, **body: {  # noqa: E731
        "task_key": key, **({"depends_on": deps} if deps else {}), **({"run_if": run_if} if run_if else {}),
        "max_retries": retries, **({"min_retry_interval_millis": 300000} if retries else {}), **body}
    dep = lambda *keys, outcome=None: [{"task_key": k, **({"outcome": outcome} if outcome else {})} for k in keys]  # noqa: E731
    pipe_task = lambda full: {"pipeline_task": {"pipeline_id": pid, "full_refresh": full}}  # noqa: E731
    snap = lambda label: nb("validate_silver_snapshot.py", client=cid, run_tag="{{job.run_id}}", label=label)  # noqa: E731
    tasks = [
        t("setup_uc", **nb("setup_uc.py", client=cid)),
        t("ingest_bronze", dep("setup_uc"), **nb("ingest_bronze.py", client=cid, run_id="{{job.run_id}}-ingest")),
        t("wait_for_pipeline_slot", dep("ingest_bronze"), **nb("wait_for_pipeline_slot.py", client=cid)),
        t("choose_first_update", dep("wait_for_pipeline_slot"),
          condition_task={"op": "EQUAL_TO", "left": jp("first_update"), "right": "full_refresh"}),
        t("update_full_refresh", dep("choose_first_update", outcome="true"), retries=2, **pipe_task(True)),
        t("update_incremental", dep("choose_first_update", outcome="false"), retries=2, **pipe_task(False)),
        t("choose_idempotency_check", dep("update_full_refresh", "update_incremental"), run_if="AT_LEAST_ONE_SUCCESS",
          condition_task={"op": "EQUAL_TO", "left": jp("idempotency_check"), "right": "true"}),
        t("snapshot_after_update", dep("choose_idempotency_check", outcome="true"), **snap("1_update")),
        t("rerun", dep("snapshot_after_update"), retries=2, **pipe_task(False)),
        t("snapshot_after_rerun", dep("rerun"), **snap("2_rerun")),
        t("full_refresh", dep("snapshot_after_rerun"), retries=2, **pipe_task(True)),
        t("snapshot_after_full_refresh", dep("full_refresh"), **snap("3_full_refresh")),
        t("validate_bronze", [{"task_key": "choose_idempotency_check", "outcome": "false"},
                              {"task_key": "snapshot_after_full_refresh"}], run_if="AT_LEAST_ONE_SUCCESS",
          **nb("validate_slice1.py", client=cid)),
        t("validate_silver", dep("validate_bronze"),
          **nb("validate_slice2.py", client=cid, run_tag="{{job.run_id}}", require_snapshots=jp("idempotency_check"))),
        t("validate_gold", dep("validate_silver"),
          **nb("validate_slice3.py", client=cid, run_tag="{{job.run_id}}", require_snapshots=jp("idempotency_check"))),
    ]
    if c.performance.measure:   # performance.measure in the client YAML
        tasks.append(t("measure_performance", dep("validate_gold"), run_if="ALL_DONE",
                       **nb("measure_performance.py", client=cid, job_run_id="{{job.run_id}}", label=jp("perf_label"))))
    return {"resources": {
        "pipelines": {pipe: {
            "name": f"keelstone-silver-gold-{cid}", "catalog": c.catalog, "schema": c.schema,
            "serverless": True, "continuous": False, "channel": "CURRENT",
            "configuration": {"keelstone.client": cid, "keelstone.config_dir": "${var.config_dir}"},
            "environment": {"dependencies": ["${var.wheel_path}"]},
            "libraries": [{"file": {"path": "../../pipelines/silver_gold.py"}}]}},
        "jobs": {f"client_{cid}": {
            "name": f"keelstone-client-{cid}", "max_concurrent_runs": 1,
            "queue": {"enabled": True},
            **({"trigger": {"pause_status": "UNPAUSED", "file_arrival": {
                "url": c.landing_root + "/", "min_time_between_triggers_seconds": 120,
                "wait_after_last_change_seconds": 120}}} if c.trigger == "file_arrival" else {}),
            "parameters": [{"name": "first_update", "default": "incremental"},
                           {"name": "idempotency_check", "default": "false"},
                           *([{"name": "perf_label", "default": "unlabelled"}] if c.performance.measure else [])],
            "tasks": tasks}},
        "dashboards": {f"gold_{cid}": {
            "display_name": f"Keelstone gold overview ({cid}, synthetic data)",
            "file_path": f"../../dashboards/{cid}.lvdash.json", "warehouse_id": "${var.warehouse_id}"}},
    }}


def main() -> None:
    template = (ROOT / "dashboards" / "gold_overview.template.json").read_text()
    out_dir = ROOT / "resources" / "clients"
    out_dir.mkdir(parents=True, exist_ok=True)
    for path in sorted((ROOT / "config" / "clients").glob("*.yml")):
        c = load_client(path.stem)
        (out_dir / f"{c.client_id}.yml").write_text(
            HEADER.format(client=c.client_id) + yaml.safe_dump(resources(c), sort_keys=False, width=120))
        dash = template.replace("__SCHEMA__", c.schema).replace("__CLIENT_NAME__", c.display_name)
        json.loads(dash)
        (ROOT / "dashboards" / f"{c.client_id}.lvdash.json").write_text(dash)
        print("rendered", c.client_id)


if __name__ == "__main__":
    main()
